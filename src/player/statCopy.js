/**
 * Текстовые описания характеристик для тултипов (игрок / лист).
 * Формулы дублируют смысл rules/loadout — при смене баланса править здесь и там.
 */
export function getStatDescriptionRu(statName, playerSheet) {
  const stats = playerSheet?.stats || {};
  const derived = playerSheet?.derived || {};
  if (statName === "STR") {
    return `СИЛ: макс HP (×8 к базе), бонус к урону рукопашной (+1 за очко), множитель крита (+0.03 за очко), формулы физ. скиллов. На панели — итог с бонусами экипировки (сейчас ${stats.STR ?? "—"}).`;
  }
  if (statName === "INT") {
    return `ИНТ: макс маны (×6 к базе), основа для магии. На панели — итог с бонусами экипировки (сейчас ${stats.INT ?? "—"}).`;
  }
  if (statName === "AGI") {
    return `ЛВК: шанс крита (+0.8% за очко), множитель крита (+0.02 за очко). На панели — итог с бонусами экипировки (сейчас ${stats.AGI ?? "—"}).`;
  }
  if (statName === "LUK") {
    return `УДЧ: шанс крита (+0.4% за очко), часть маг. формул, лучшие тиры лута из сундуков. На панели — итог с бонусами экипировки (сейчас ${stats.LUK ?? "—"}).`;
  }
  if (statName === "HP_MAX") {
    return `HP МАКС: сейчас ${stats.HP_MAX ?? "—"}. Считается как 100 + СИЛ×8 плюс временные бонусы от расходников; броня и амулеты к потолку HP не дают.`;
  }
  if (statName === "WEAPON_DM") {
    return "Базовый урон оружия для рукопашной атаки (без СИЛ). «Без оружия» — значение по умолчанию.";
  }
  if (statName === "HP") {
    return "HP: текущее здоровье. При 0 персонаж проигрывает забег.";
  }
  if (statName === "CRIT_CHANCE") {
    return `КРИТ %: для рукопашной атаки — база оружия + ЛВК×0.8 + УДЧ×0.4 (макс 75%). Сейчас: ${derived.CRIT_CHANCE ?? 0}%.`;
  }
  if (statName === "CRIT_MULT") {
    return `КРИТ Х: для рукопашной — база оружия + ЛВК×0.02 + СИЛ×0.03. Сейчас: x${derived.CRIT_MULT ?? 1}.`;
  }
  return "Характеристика персонажа.";
}
